# ===== Prompt Injection Defense =====


def sanitize_user_input(text: str) -> str:
    """
    Sanitize user input to prevent prompt injection attacks.

    Removes or escapes patterns commonly used in prompt injection:
    - System instruction patterns
    - Role assumption attempts
    - Meta-instruction patterns

    Args:
        text: Raw user input

    Returns:
        Sanitized text safe for prompt interpolation
    """
    if not text:
        return ""

    # Patterns that may indicate prompt injection attempts
    injection_patterns = [
        r"(?i)ignore\s+(all\s+)?previous\s+(instructions?|prompts?|rules?)",
        r"(?i)disregard\s+(all\s+)?previous\s+",
        r"(?i)you\s+are\s+now\s+(a|an)\s+",
        r"(?i)new\s+instructions?\s*:",
        r"(?i)system\s*:\s*",
        r"(?i)assistant\s*:\s*",
        r"(?i)user\s*:\s*",
        r"(?i)\[SYSTEM\]",
        r"(?i)\[INST\]",
        r"(?i)<<SYS>>",
        r"(?i)<\|im_start\|>",
        r"(?i)forget\s+(everything|all)\s+(you\s+)?know",
    ]

    sanitized = text
    for pattern in injection_patterns:
        sanitized = re.sub(pattern, "[FILTERED]", sanitized)

    return sanitized


def wrap_user_content(content: str, label: str = "user_input") -> str:
    """
    Wrap user-provided content in XML tags for clear delimitation.

    This helps LLMs understand that the content is user data,
    not system instructions, reducing prompt injection risk.

    Args:
        content: User-provided content to wrap
        label: Tag name for the wrapper

    Returns:
        Content wrapped in XML-style tags
    """
    sanitized = sanitize_user_input(content)
    return f"<{label}>\n{sanitized}\n</{label}>"


